-- Migration 010: Property Tax Computations and Reports
-- Replaces tax billing and cashier dependency with informational tax computation reports (3NF compliant)

CREATE TABLE IF NOT EXISTS property_tax_computations (
  computation_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  computation_number VARCHAR(50) NOT NULL UNIQUE,
  property_id INT UNSIGNED NOT NULL,
  property_type ENUM('lot', 'building', 'land') NOT NULL DEFAULT 'lot',
  target_id_int INT UNSIGNED DEFAULT NULL,
  target_id_str VARCHAR(100) DEFAULT NULL,
  tax_declaration_id INT UNSIGNED DEFAULT NULL,
  owner_id INT UNSIGNED NOT NULL,
  tax_year INT NOT NULL,
  classification VARCHAR(100) NOT NULL DEFAULT 'Residential',
  actual_use VARCHAR(100) DEFAULT 'Residential',
  market_value DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
  assessment_level DECIMAL(6, 4) NOT NULL DEFAULT 0.2000,
  assessed_value DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
  basic_tax_rate DECIMAL(6, 4) NOT NULL DEFAULT 0.0100,
  basic_tax_amount DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
  sef_tax_rate DECIMAL(6, 4) NOT NULL DEFAULT 0.0100,
  sef_tax_amount DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
  other_levies_amount DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
  other_levies_details JSON DEFAULT NULL,
  discount_rate DECIMAL(6, 4) NOT NULL DEFAULT 0.0000,
  discount_amount DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
  penalty_interest_rate DECIMAL(6, 4) NOT NULL DEFAULT 0.0000,
  penalty_interest_amount DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
  months_delayed INT NOT NULL DEFAULT 0,
  prior_delinquency_amount DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
  total_computed_tax DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
  computation_status ENUM('draft', 'pending_approval', 'approved', 'rejected') NOT NULL DEFAULT 'draft',
  is_complete TINYINT(1) NOT NULL DEFAULT 1,
  incomplete_reason VARCHAR(255) DEFAULT NULL,
  rejection_reason TEXT DEFAULT NULL,
  rule_version_snapshot JSON DEFAULT NULL,
  computed_by_user_id INT UNSIGNED NOT NULL,
  reviewed_by_user_id INT UNSIGNED DEFAULT NULL,
  reviewed_at DATETIME DEFAULT NULL,
  notes TEXT DEFAULT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_prop (property_id),
  INDEX idx_owner (owner_id),
  INDEX idx_td (tax_declaration_id),
  INDEX idx_year (tax_year),
  INDEX idx_status (computation_status),
  FOREIGN KEY (property_id) REFERENCES properties(property_id) ON DELETE CASCADE,
  FOREIGN KEY (owner_id) REFERENCES property_owners(owner_id) ON DELETE RESTRICT,
  FOREIGN KEY (computed_by_user_id) REFERENCES users(user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
